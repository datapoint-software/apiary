    public static IReadOnlyCollection<string> Codes => s_descriptions.Keys;

    public static string Describe(string code, IReadOnlyDictionary<string, object?>? parameters) =>
        s_descriptions.TryGetValue(code, out var template)
            ? Placeholder().Replace(template, match => Value(parameters, match.Groups["name"].Value) ?? match.Value)
            : $"No description for {code}. The code and its parameters are the contract.";

    private static string? Value(IReadOnlyDictionary<string, object?>? parameters, string name) =>
        parameters is not null && parameters.TryGetValue(name, out var value) && value is not null
            ? Convert.ToString(value, CultureInfo.InvariantCulture)
            : null;

    [GeneratedRegex(@"\{(?<name>[a-zA-Z]+)\}", RegexOptions.ExplicitCapture, matchTimeoutMilliseconds: 100)]
    private static partial Regex Placeholder();
