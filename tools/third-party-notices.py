"""Writes THIRD-PARTY-NOTICES.txt: the notices for the NuGet packages Apiary's server ships.

It reads the packages from src/*/packages.lock.json and their license, copyright and source from
the restored packages, so run `dotnet restore` first. Build-time packages (PrivateAssets="all")
are left out.

Only the licenses in tools/licenses/ are accepted. A package under any other license fails the
script until someone has reviewed it, including whether it allows Apiary to be offered under other
terms, and added the license's text there.

Usage: python3 tools/third-party-notices.py [--check]
--check writes nothing and fails if the file isn't up to date.
"""
import glob
import json
import os
import re
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(TOOLS)
OUTPUT = os.path.join(REPO, "THIRD-PARTY-NOTICES.txt")
LICENSES = os.path.join(TOOLS, "licenses")
NOTICE_FILES = re.compile(r"^(notice|third-party-notices)(\.[a-z]+)?$", re.IGNORECASE)


def packages_folder():
    return os.environ.get("NUGET_PACKAGES") or os.path.join(os.path.expanduser("~"), ".nuget", "packages")


def build_time_packages():
    names = set()
    for path in [os.path.join(REPO, "Directory.Build.props"), *glob.glob(os.path.join(REPO, "src", "*", "*.csproj"))]:
        with open(path, encoding="utf-8") as f:
            for match in re.finditer(r'<PackageReference\s+Include="([^"]+)"[^>]*PrivateAssets="all"', f.read()):
                names.add(match.group(1).lower())
    return names


def shipped_packages():
    excluded = build_time_packages()
    found = {}
    for path in sorted(glob.glob(os.path.join(REPO, "src", "*", "packages.lock.json"))):
        with open(path, encoding="utf-8") as f:
            for dependencies in json.load(f)["dependencies"].values():
                for name, info in dependencies.items():
                    if info.get("type") != "Project" and name.lower() not in excluded:
                        found[(name.lower(), info["resolved"])] = name
    return [(name, version) for (_, version), name in sorted(found.items())]


def describe(name, version):
    folder = os.path.join(packages_folder(), name.lower(), version)
    nuspecs = glob.glob(os.path.join(folder, "*.nuspec"))
    if not nuspecs:
        sys.exit(f"{name} {version} isn't restored in {packages_folder()}. Run dotnet restore first.")
    with open(nuspecs[0], encoding="utf-8-sig") as f:
        nuspec = f.read()

    def element(pattern):
        match = re.search(pattern, nuspec)
        return match.group(1).strip() if match else None

    license = element(r'<license type="expression">([^<]+)</license>')
    if license is None or not os.path.isfile(os.path.join(LICENSES, license + ".txt")):
        sys.exit(f"{name} {version} is under {license or 'a license without an SPDX expression'}, which isn't in "
                 "tools/licenses/. Review it, then add its text there.")
    notices = [os.path.join(folder, entry) for entry in sorted(os.listdir(folder)) if NOTICE_FILES.match(entry)]
    return {
        "name": name,
        "version": version,
        "license": license,
        "copyright": element(r"<copyright>([^<]+)</copyright>") or element(r"<authors>([^<]+)</authors>"),
        "source": element(r'<repository[^>]*\surl="([^"]+)"') or element(r"<projectUrl>([^<]+)</projectUrl>"),
        "notices": notices,
    }


def heading(text, underline):
    return f"{text}\n{underline * min(len(text), 72)}"


def render(packages):
    out = [
        heading("Third-party notices for Apiary's server", "="),
        "",
        "Apiary's server includes the NuGet packages below. The admin interface's packages are",
        "listed in wwwroot/3rdpartylicenses.txt, and the .NET runtime's in its own",
        "THIRD-PARTY-NOTICES.TXT.",
        "",
        "Generated by tools/third-party-notices.py. Don't edit it by hand.",
        "",
        "",
        heading("Packages", "-"),
    ]
    for p in packages:
        out += [f"{p['name']} {p['version']}", f"  License: {p['license']}"]
        if p["copyright"]:
            out.append(f"  Copyright: {p['copyright']}")
        if p["source"]:
            out.append(f"  Source: {p['source']}")
        out.append("")

    for license in sorted({p["license"] for p in packages}):
        with open(os.path.join(LICENSES, license + ".txt"), encoding="utf-8") as f:
            text = f.read().rstrip("\n")
        users = ", ".join(p["name"] for p in packages if p["license"] == license)
        out += ["", heading(f"{license} license", "-"), f"Applies to: {users}.", "", text, ""]

    # Packages built from the same repository ship the same notices: keep each text once.
    notices = {}
    for p in packages:
        for path in p["notices"]:
            with open(path, encoding="utf-8-sig") as f:
                text = f.read().replace("\r\n", "\n").rstrip("\n")
            notices.setdefault(text, []).append(p["name"])
    for text, users in notices.items():
        out += ["", heading("Notices shipped with " + ", ".join(users), "-"), text, ""]

    return "\n".join(out).rstrip("\n") + "\n"


def main():
    content = render([describe(name, version) for name, version in shipped_packages()])
    if "--check" in sys.argv[1:]:
        current = open(OUTPUT, encoding="utf-8").read() if os.path.exists(OUTPUT) else None
        if current != content:
            sys.exit("THIRD-PARTY-NOTICES.txt is out of date. Run python3 tools/third-party-notices.py.")
        print("THIRD-PARTY-NOTICES.txt is up to date.")
        return
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"wrote THIRD-PARTY-NOTICES.txt ({content.count(chr(10))} lines)")


main()
